def occupation_label_for_user(user_id, occupation):
    raw_value = "" if occupation is None else str(occupation).strip()
    if raw_value:
        return MOVIELENS_OCCUPATIONS.get(raw_value, raw_value)
    try:
        index = int(user_id) % len(DEMO_OCCUPATIONS)
    except (TypeError, ValueError):
        index = 0
    return DEMO_OCCUPATIONS[index]
